//! Persistence of the hung items (`state.json`) plus the startup existence check.
//!
//! Design spec 4.5: only the items (paths and metadata) are persisted, as a bare JSON array. The
//! settings live in their own `settings.json`; monitors and the app version are rebuilt at runtime.
//! On startup every row's `path` is checked and rows whose file disappeared are dropped — history is
//! never re-hung (Tendedero baseline strategy).
//!
//! Writes go through the same atomic `.tmp` + rename path as the settings (see
//! [`crate::settings::write_atomic`]).

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use anyhow::Context;

use crate::item::Item;
use crate::settings::{backup_corrupt, write_atomic};

/// File name of the item document inside the Hangline data directory.
const STATE_FILE: &str = "state.json";

/// Absolute path of the persisted item list inside `dir`.
pub fn state_path(dir: &Path) -> PathBuf {
    dir.join(STATE_FILE)
}

/// Loads the persisted items, dropping the ones whose files are gone.
///
/// Kept as the plain read entry point from the task contract; `AppState` uses
/// [`load_and_prune`] because it also needs the dropped ids for the startup rewrite.
#[allow(dead_code)] // Task 8/13 startup callers; the unit tests cover it today.
pub fn load(dir: &Path) -> Vec<Item> {
    load_and_prune(dir).0
}

/// Loads the persisted items and prunes rows whose `path` no longer exists.
///
/// Returns the remaining items sorted by `added_at` ascending (oldest left, newest right) and the
/// ids of the dropped rows in file order. A missing file is a normal first run and yields an empty
/// list; an unreadable file is preserved as `state.json.corrupt` (then treated as empty) so a bad
/// file cannot wedge every subsequent start.
pub fn load_and_prune(dir: &Path) -> (Vec<Item>, Vec<String>) {
    let path = state_path(dir);
    let mut items = match fs::read(&path) {
        Ok(bytes) => match serde_json::from_slice::<Vec<Item>>(&bytes) {
            Ok(items) => {
                log::info!(
                    "store: loaded {} item(s) from {}",
                    items.len(),
                    path.display()
                );
                items
            }
            Err(err) => {
                log::error!(
                    "store: {} is not a valid item list ({err}); starting empty",
                    path.display()
                );
                backup_corrupt(&path);
                Vec::new()
            }
        },
        Err(err) if err.kind() == io::ErrorKind::NotFound => {
            log::info!(
                "store: {} does not exist yet; starting empty",
                path.display()
            );
            Vec::new()
        }
        Err(err) => {
            log::error!(
                "store: failed to read {} ({err}); starting empty",
                path.display()
            );
            Vec::new()
        }
    };

    let removed = prune(&mut items);
    if !removed.is_empty() {
        log::info!(
            "store: dropped {} item(s) whose files are gone",
            removed.len()
        );
    }
    // P2-7: a persisted thumbnail is only kept while the cached file still exists; a cleaned or
    // migrated cache is regenerated by the startup backfill instead of serving a dead asset URL.
    let mut thumbs_dropped = 0;
    for item in &mut items {
        let Some(thumb) = item.thumb_path.as_ref() else {
            continue;
        };
        if !thumb.exists() {
            item.thumb_path = None;
            thumbs_dropped += 1;
        }
    }
    if thumbs_dropped > 0 {
        log::info!(
            "store: dropped {thumbs_dropped} stale thumbnail path(s); the backfill will rebuild them"
        );
    }
    // Spec 4.5: items are ordered by added_at ascending (the newest hangs on the right).
    items.sort_by_key(|item| item.added_at);
    (items, removed)
}

/// Removes items whose file no longer exists and returns their ids in list order.
pub fn prune(items: &mut Vec<Item>) -> Vec<String> {
    let mut removed = Vec::new();
    items.retain(|item| {
        if item.path.exists() {
            true
        } else {
            removed.push(item.id.clone());
            false
        }
    });
    removed
}

/// Writes the item list atomically (`.tmp` + rename, best-effort `fsync`).
pub fn save_atomic(dir: &Path, items: &[Item]) -> anyhow::Result<()> {
    let bytes = serde_json::to_vec_pretty(items).context("failed to serialize items")?;
    write_atomic(&state_path(dir), &bytes)
}

#[cfg(test)]
mod tests {
    use super::*;

    use std::fs;
    use std::path::{Path, PathBuf};

    use serde_json::json;

    use crate::item::{Item, ItemKind};

    /// Scratch directory under `target/` (git-ignored); never touches `%LOCALAPPDATA%`.
    fn test_dir(tag: &str) -> PathBuf {
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("target")
            .join("store-tests")
            .join(format!("{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).expect("create the store test dir");
        dir
    }

    /// Creates a real file so the item survives the startup existence check.
    fn existing_file(dir: &Path, name: &str) -> PathBuf {
        let path = dir.join(name);
        fs::write(&path, b"item bytes").expect("create the test file");
        path
    }

    /// Builds a persisted item without touching the filesystem.
    fn item(id: &str, path: &Path, added_at: i64) -> Item {
        Item {
            id: id.to_string(),
            path: path.to_path_buf(),
            thumb_path: None,
            kind: ItemKind::Capture,
            hash: 1,
            width: 10,
            height: 20,
            created_at: 0,
            added_at,
            updated_at: added_at,
        }
    }

    #[test]
    fn save_and_load_round_trip_sorts_by_added_at() {
        let dir = test_dir("round-trip");
        let a = item("a", &existing_file(&dir, "a.png"), 200);
        let b = item("b", &existing_file(&dir, "b.png"), 100);

        save_atomic(&dir, &[a.clone(), b.clone()]).expect("save items");
        assert!(
            !dir.join("state.json.tmp").exists(),
            "the .tmp file must be renamed away"
        );

        // state.json is a bare items array with camelCase Item fields (spec 4.5).
        let json: serde_json::Value =
            serde_json::from_slice(&fs::read(dir.join("state.json")).expect("read state"))
                .expect("valid JSON");
        let items = json.as_array().expect("state.json is a bare items array");
        assert_eq!(items.len(), 2);
        assert_eq!(items[0]["kind"], json!("capture"));
        assert!(items[0].get("createdAt").is_some());
        assert!(items[0].get("addedAt").is_some());

        // Items are ordered by added_at ascending (oldest left, newest right).
        assert_eq!(load(&dir), vec![b, a]);
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn load_filters_items_whose_files_are_gone() {
        let dir = test_dir("filter");
        let kept = item("kept", &existing_file(&dir, "kept.png"), 100);
        let gone = item("gone", &dir.join("gone.png"), 200);
        save_atomic(&dir, &[kept.clone(), gone]).expect("save items");

        assert_eq!(load(&dir), vec![kept.clone()]);

        let (items, removed) = load_and_prune(&dir);
        assert_eq!(items, vec![kept]);
        assert_eq!(removed, vec!["gone".to_string()]);
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn load_missing_file_is_empty_and_never_writes() {
        let dir = test_dir("missing");
        assert!(load(&dir).is_empty());
        assert!(
            !dir.join("state.json").exists(),
            "a read must not seed an empty state file"
        );
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn load_corrupt_file_is_empty_and_keeps_a_backup() {
        let dir = test_dir("corrupt");
        let corrupt = b"this is not a state file";
        fs::write(dir.join("state.json"), corrupt).expect("write corrupt state");

        assert!(load(&dir).is_empty());
        assert_eq!(
            fs::read(dir.join("state.json.corrupt")).expect("corrupt backup"),
            corrupt
        );
        assert!(
            !dir.join("state.json").exists(),
            "the unreadable file must be moved aside, not left behind"
        );
        let _ = fs::remove_dir_all(dir);
    }

    /// Task 13 contract: a prune pass keeps existing files and drops the ones that are gone.
    #[test]
    fn prune_drops_items_whose_files_are_gone() {
        let dir = test_dir("prune-contract");
        let keep = existing_file(&dir, "keep.png");
        let gone = dir.join("gone.png");
        let mut items = vec![item("keep", &keep, 1), item("gone", &gone, 2)];

        let removed = prune(&mut items);
        assert_eq!(removed, vec!["gone".to_string()]);
        assert_eq!(items, vec![item("keep", &keep, 1)]);
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn prune_removes_missing_files_and_returns_their_ids_in_order() {
        let dir = test_dir("prune");
        let kept_path = existing_file(&dir, "kept.png");
        let mut items = vec![
            item("gone-a", &dir.join("a.png"), 1),
            item("kept", &kept_path, 2),
            item("gone-b", &dir.join("b.png"), 3),
        ];

        let removed = prune(&mut items);
        assert_eq!(removed, vec!["gone-a".to_string(), "gone-b".to_string()]);
        assert_eq!(items, vec![item("kept", &kept_path, 2)]);
        assert!(prune(&mut items).is_empty(), "prune is idempotent");
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn stale_thumbnail_paths_are_dropped_on_load() {
        // P2-7: a persisted thumbPath survives while the cache file exists; a cleaned cache entry
        // is dropped on load so the startup backfill can rebuild it instead of serving a dead URL.
        let dir = test_dir("thumb-validate");
        let source = existing_file(&dir, "shot.png");
        let thumb = existing_file(&dir, "thumb.png");
        let mut with_thumb = item("with-thumb", &source, 1);
        with_thumb.thumb_path = Some(thumb.clone());
        let mut stale = item("stale", &source, 2);
        stale.thumb_path = Some(dir.join("missing-thumb.png"));
        save_atomic(&dir, &[with_thumb, stale]).expect("seed state");

        let items = load(&dir);
        assert_eq!(items.len(), 2);
        assert_eq!(items[0].thumb_path, Some(thumb));
        assert_eq!(items[1].thumb_path, None, "a missing thumb is dropped");

        // Round-trip: an existing thumbPath is serialized and read back verbatim.
        assert!(load(&dir)[0].thumb_path.is_some());
        assert!(!dir.join("state.json.tmp").exists());
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn save_atomic_replaces_existing_state() {
        let dir = test_dir("replace");
        let a = item("a", &existing_file(&dir, "a.png"), 100);
        let b = item("b", &existing_file(&dir, "b.png"), 200);

        save_atomic(&dir, &[a]).expect("first save");
        save_atomic(&dir, &[b.clone()]).expect("second save");
        assert_eq!(load(&dir), vec![b]);
        assert!(!dir.join("state.json.tmp").exists());
        let _ = fs::remove_dir_all(dir);
    }
}
